test('비밀번호로 토큰을 복원하고 암호문·아이디 변조와 잘못된 비밀번호를 거부한다',async()=>{
  const token='dummy-auth-test-token';
  const account=await encryptAdmin('admin','admin',token);
  const db={version:1,accounts:[account]};
  assert.equal(await decryptAdmin(db,' ADMIN ','admin'),token);
  assert.ok(!serializeAccounts(db).includes(token));
  assert.equal(Object.hasOwn(account,'password'),false);
  await assert.rejects(decryptAdmin(db,'admin','wrong'),/아이디 또는 비밀번호/);
  await assert.rejects(decryptAdmin(db,'missing','admin'),/아이디 또는 비밀번호/);
  const tampered={...account,ciphertext:(account.ciphertext[0]==='A'?'B':'A')+account.ciphertext.slice(1)};
  await assert.rejects(decryptAdmin({version:1,accounts:[tampered]},'admin','admin'),/아이디 또는 비밀번호/);
  await assert.rejects(decryptAdmin({version:1,accounts:[{...account,id:'other'}]},'other','admin'),/아이디 또는 비밀번호/);
});
test('같은 비밀번호도 독립된 암호문으로 저장하고 관리자 추가와 중복 검사를 한다',async()=>{
  const token='dummy-auth-test-token';
  const first=await encryptAdmin('admin','admin',token);
  const second=await encryptAdmin('admin','admin',token);
  assert.notEqual(first.salt,second.salt);assert.notEqual(first.iv,second.iv);assert.notEqual(first.ciphertext,second.ciphertext);
  const original={version:1,accounts:[first]};
  const db=await addAdmin(original,'editor','editor-password',token);
  assert.equal(original.accounts.length,1);assert.equal(db.accounts.length,2);
  assert.equal(await decryptAdmin(db,'editor','editor-password'),token);
  const remaining=removeAdmin(db,'admin');
  assert.equal(await decryptAdmin(remaining,'editor','editor-password'),token);
  assert.throws(()=>removeAdmin(remaining,'editor'),/최소 1명/);
  await assert.rejects(addAdmin(db,'ADMIN','other',token),/이미 사용 중/);
  await assert.rejects(addAdmin(db,'new','',token),/비밀번호/);
  const many={version:1,accounts:Array.from({length:2001},(_,i)=>({...first,id:`admin${i}`}))};
  assert.equal(validateAccounts(many).accounts.length,2001);
});
test('마지막 관리자 삭제는 함수·편집 검증·GitHub 저장 요청 모두에서 차단한다',async()=>{
  const account=await encryptAdmin('admin','admin','dummy');
  const db={version:1,accounts:[account]};
  assert.throws(()=>removeAdmin(db,'admin'),/최소 1명/);
  const two={version:1,accounts:[account,{...account,id:'other'}]};
  assert.deepEqual(removeAdmin(two,'admin').accounts.map(a=>a.id),['other']);
  const baseline={[ADMIN_ACCOUNTS_PATH]:{sha:'old',text:serializeAccounts(db)}};
  assert.throws(()=>validateEdits(baseline,{[ADMIN_ACCOUNTS_PATH]:null}),/최소 1명/);
  assert.throws(()=>validateEdits(baseline,{[ADMIN_ACCOUNTS_PATH]:{text:'{"version":1,"accounts":[]}'}}),/최소 1명/);
  const calls=[];const client=createGitHubClient({token:'dummy'},async()=>{calls.push('called');});
  await assert.rejects(client.publish(baseline,{[ADMIN_ACCOUNTS_PATH]:null}),/최소 1명/);
  await assert.rejects(client.publish(baseline,{[ADMIN_ACCOUNTS_PATH]:{text:'{"version":1,"accounts":[]}'}}),/최소 1명/);
  assert.equal(calls.length,0);
});
test('관리자 자료 형식과 동시 수정을 검증하고 평문 토큰·비밀번호 필드를 거부한다',async()=>{
  const account=await encryptAdmin('admin','admin','dummy');
  const db={version:1,accounts:[account]};
  assert.ok(isContentPath(ADMIN_ACCOUNTS_PATH));assert.equal(isContentPath('public/admin/other.json'),false);
  assert.deepEqual(readAccounts(serializeAccounts(db)),db);
  assert.throws(()=>readAccounts(JSON.stringify({...db,token:'plaintext'})),/자료/);
  assert.throws(()=>validateAccounts({version:1,accounts:[{...account,iterations:1}]}),/암호화/);
  assert.throws(()=>validateAccounts({version:1,accounts:[{...account,password:'plaintext'}]}),/암호화 정보만/);
  assert.throws(()=>assertUnchanged({[ADMIN_ACCOUNTS_PATH]:{sha:'old'}},{tree:[{path:ADMIN_ACCOUNTS_PATH,sha:'new',mode:'100644'}]}),/덮어쓰지/);
});
test('관리자 변경을 공개 편집 자료에 포함하고 빌드도 빈 관리자 목록을 거부한다',async t=>{
  const root=await fs.mkdtemp(path.join(os.tmpdir(),'starflower-accounts-'));t.after(()=>fs.rm(root,{recursive:true,force:true}));
  await fs.mkdir(path.join(root,'content'),{recursive:true});await fs.mkdir(path.join(root,'public/admin'),{recursive:true});
  const db={version:1,accounts:[await encryptAdmin('admin','admin','dummy-admin-token')]};
  const text=serializeAccounts(db);
  await fs.writeFile(path.join(root,ADMIN_ACCOUNTS_PATH),text);
  await generateContent({root,quiet:true});
  const snapshot=JSON.parse(await fs.readFile(path.join(root,'public/data/admin.json'),'utf8'));
  assert.equal(snapshot.files[ADMIN_ACCOUNTS_PATH].text,text);
  assert.equal(await decryptAdmin(readAccounts(snapshot.files[ADMIN_ACCOUNTS_PATH].text),'admin','admin'),'dummy-admin-token');
  await fs.writeFile(path.join(root,ADMIN_ACCOUNTS_PATH),'{"version":1,"accounts":[]}');
  await assert.rejects(generateContent({root,quiet:true}),/최소 1명/);
});
test('본인 비밀번호 변경은 같은 토큰을 새 암호문으로 보관하고 다른 관리자와 원본 자료를 유지한다',async()=>{
  const token='dummy-password-change-token';
  const original={version:1,accounts:[await encryptAdmin('admin','old-password',token),await encryptAdmin('editor','editor-password',token)]};
  const before=serializeAccounts(original);
  const changed=await changeAdminPassword(original,'admin','old-password','new-password','new-password');
  assert.equal(serializeAccounts(original),before);
  assert.equal(changed.accounts.length,2);
  assert.deepEqual(changed.accounts[1],original.accounts[1]);
  assert.notEqual(changed.accounts[0].salt,original.accounts[0].salt);
  assert.notEqual(changed.accounts[0].iv,original.accounts[0].iv);
  assert.equal(await decryptAdmin(changed,'admin','new-password'),token);
  await assert.rejects(decryptAdmin(changed,'admin','old-password'),/아이디 또는 비밀번호/);
  assert.equal(await decryptAdmin(changed,'editor','editor-password'),token);
  assert.ok(!serializeAccounts(changed).includes(token));
  assert.ok(!serializeAccounts(changed).includes('new-password'));
  const second=await changeAdminPassword(changed,'admin','old-password','next-password','next-password',{authenticationDatabase:original});
  assert.equal(await decryptAdmin(second,'admin','next-password'),token);
  assert.deepEqual(second.accounts[1],original.accounts[1]);
});
test('비밀번호 변경은 현재 비밀번호 오류·확인 불일치·빈 비밀번호·삭제 예정 계정을 거부한다',async()=>{
  const original={version:1,accounts:[await encryptAdmin('admin','old-password','dummy')]};
  const before=serializeAccounts(original);
  await assert.rejects(changeAdminPassword(original,'admin','wrong','new','new'),/현재 비밀번호/);
  await assert.rejects(changeAdminPassword(original,'admin','old-password','new','different'),/확인/);
  await assert.rejects(changeAdminPassword(original,'admin','old-password',' ',' '),/새 비밀번호/);
  await assert.rejects(changeAdminPassword(original,'missing','old-password','new','new'),/삭제 예정/);
  assert.equal(serializeAccounts(original),before);
});
